// What each route accepts. Every request is checked here before it reaches the
// database, so a wrong type or an oversized value is a clear 400 instead of a
// crash, and unknown fields are dropped. Messages are written for the people
// using the app, because the client shows them as they are.
const { z } = require("zod");

const EMAIL_MAX_LENGTH = 254; // the longest address email standards allow
const PASSWORD_MIN_LENGTH = 8;
const PASSWORD_MAX_BYTES = 72; // bcrypt ignores anything after the first 72 bytes
const TITLE_MAX_LENGTH = 200;
const MESSAGE_MAX_LENGTH = 10_000;
const MAX_YEARS_AHEAD = 50;

// Messages for a field that is missing or isn't a string.
const text = (label) => ({
  error: (issue) => (issue.input === undefined ? `${label} is required` : `${label} must be text`),
});

const body = (shape) => z.object(shape, { error: "The request body must be a JSON object" });

// Emails are compared in lowercase, so Ada@Example.com and ada@example.com are
// the same account.
const email = z
  .string(text("Email"))
  .trim()
  .toLowerCase()
  .min(1, { error: "Email is required" })
  .max(EMAIL_MAX_LENGTH, { error: `Email must be at most ${EMAIL_MAX_LENGTH} characters` })
  .pipe(z.email({ error: "Enter a valid email address" }));

// Passwords are used exactly as typed: never trimmed or lowercased.
const newPassword = z
  .string(text("Password"))
  .min(PASSWORD_MIN_LENGTH, {
    error: `Password must be at least ${PASSWORD_MIN_LENGTH} characters`,
  })
  .refine((value) => Buffer.byteLength(value, "utf8") <= PASSWORD_MAX_BYTES, {
    error: `Password must be at most ${PASSWORD_MAX_BYTES} bytes (accented letters and emoji count as 2 to 4 bytes each)`,
  });

const signupBody = body({ email, password: newPassword });

// Login takes any password: a wrong one simply doesn't match.
const loginBody = body({
  email,
  password: z.string(text("Password")).min(1, { error: "Password is required" }),
});

// The token from an emailed link. Any short string passes: one that isn't a
// working link is answered like an expired one.
const linkToken = z.string(text("Token")).max(100, { error: "Token is too long" });

const verifyEmailBody = body({ token: linkToken });

const forgotPasswordBody = body({ email });

const resetPasswordBody = body({ token: linkToken, password: newPassword });

const yearsFromNow = (years) => {
  const date = new Date();
  date.setUTCFullYear(date.getUTCFullYear() + years);
  return date;
};

const trimmedText = (label, maxLength) =>
  z
    .string(text(label))
    .trim()
    .min(1, { error: `${label} is required` })
    .max(maxLength, {
      error: `${label} must be at most ${maxLength.toLocaleString("en-US")} characters`,
    });

// An instant, so it must say which time zone it is in: "Z" (UTC) or an offset
// such as +05:30. A bare "2030-01-01T09:00" would be read in the server's zone.
const unlockDate = z.iso
  .datetime({
    offset: true,
    error: (issue) =>
      issue.input === undefined
        ? "Unlock date is required"
        : "Unlock date must be a date and time with a time zone, like 2030-01-01T09:00:00Z",
  })
  .transform((value) => new Date(value))
  .refine((date) => date > new Date(), { error: "Unlock date must be in the future" })
  .refine((date) => date <= yearsFromNow(MAX_YEARS_AHEAD), {
    error: `Unlock date must be at most ${MAX_YEARS_AHEAD} years from now`,
  });

// The client also sends `email`; it is dropped (with any other unknown field)
// until Phase 3 decides what it means.
const newCapsuleBody = body({
  title: trimmedText("Title", TITLE_MAX_LENGTH),
  message: trimmedText("Message", MESSAGE_MAX_LENGTH),
  unlockDate,
  // A real boolean: the string "false" is rejected rather than read as true.
  isPublic: z.boolean({ error: "isPublic must be true or false" }).default(false),
});

const MAX_ID = 2_147_483_647; // the largest value of a PostgreSQL integer column

// Ids in URLs (/capsules/:id): a positive whole number written plainly, so
// "1e3", "0x10", "-1" and values too big for the database are all rejected.
const capsuleIdParams = z.object({
  id: z
    .string()
    .regex(/^[1-9][0-9]*$/, { error: "Invalid capsule id" })
    .transform(Number)
    .refine((id) => id <= MAX_ID, { error: "Invalid capsule id" }),
});

// Share-link slugs are UUIDs generated by the database; anything else can't exist.
const slug = z.uuid();
const isSlug = (value) => slug.safeParse(value).success;

module.exports = {
  signupBody,
  loginBody,
  verifyEmailBody,
  forgotPasswordBody,
  resetPasswordBody,
  newCapsuleBody,
  capsuleIdParams,
  isSlug,
};
